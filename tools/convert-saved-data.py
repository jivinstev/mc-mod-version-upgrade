def self_check():
    ok = True

    def expect(cond, label):
        nonlocal ok
        if not cond:
            print("FAIL:", label)
            ok = False

    with tempfile.TemporaryDirectory() as d:
        src = pathlib.Path(d)
        for rel, body in SAMPLE.items():
            (src / rel).parent.mkdir(parents=True, exist_ok=True)
            (src / rel).write_text(body, encoding="utf-8")
        convert(src, "x")
        bans = (src / "a/Bans.java").read_text(encoding="utf-8")
        expect("public class Bans extends a.compat.SavedDataCompat.Base {" in bans, "extends rewritten")
        expect("@Override\n   public CompoundTag save(CompoundTag tag, HolderLookup.Provider provider) {" in bans, "save kept")
        expect('computeIfAbsent(a.compat.SavedDataCompat.type(new a.compat.SavedDataCompat.Factory<>(Bans::new, Bans::load), "x_bans"))'
               in bans, "computeIfAbsent wrapped")
        expect("// reached through level.getDataStorage().computeIfAbsent(...) at runtime" in bans, "a comment is untouched")
        expect(re.search(r'computeIfAbsent\(a\.compat\.SavedDataCompat\.type\(new a\.compat\.SavedDataCompat\.Factory<>\('
                         r'\s*Bans::new,\s*\(tag, registries\) -> load\(tag, registries\)\s*\), "x_other"\)\)', bans), "lambda loader")
        expect('cache.computeIfAbsent("k", k -> 1);' in bans and 'cache.get("k");' in bans, "a Map is untouched")
        sched = (src / "a/Sched.java").read_text(encoding="utf-8")
        expect("import a.compat.SavedDataCompat.Factory;" in sched, "nested Factory import")
        expect("import net.minecraft.world.level.storage.SavedDataStorage;" in sched, "storage import")
        expect("SavedDataStorage storage = level.getDataStorage();" in sched, "storage type")
        expect('storage.get(a.compat.SavedDataCompat.type(FACTORY, "event_scheduler"))' in sched, "get on a variable")
        expect('storage.computeIfAbsent(a.compat.SavedDataCompat.type(FACTORY, "event_scheduler"))' in sched, "multi-line call")
        expect('storage.set("event_scheduler", found);' in sched, "set left alone")
        ev = (src / "a/Event.java").read_text(encoding="utf-8")
        expect("extends a.compat.SavedDataCompat.Base" in ev and "new a.compat.SavedDataCompat.Factory<>(Event.Data::new" in ev,
               "fully qualified forms")
        gen = (src / "a/compat/SavedDataCompat.java").read_text(encoding="utf-8")
        expect('NAMESPACE = "x"' in gen and "package a.compat;" in gen, "compat generated")
        expect(gen.count("{") == gen.count("}"), "compat braces balance")
        snap = {p: p.read_text(encoding="utf-8") for p in src.rglob("*.java")}
        convert(src, "x")
        expect(snap == {p: p.read_text(encoding="utf-8") for p in src.rglob("*.java")}, "idempotent")
    print("self-check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src")
    ap.add_argument("--modid")
    ap.add_argument("--package", help="where SavedDataCompat goes (default: <the @Mod class's package>.compat)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--self-check", action="store_true")
    a = ap.parse_args()
    if a.self_check:
        return self_check()
    if not (a.src and a.modid):
        ap.error("--src and --modid are required")
    return convert(a.src, a.modid, a.package, a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
