def self_check():
    ok = True

    def chk(label, cond):
        nonlocal ok
        if not cond:
            print("FAIL:", label)
            ok = False

    with tempfile.TemporaryDirectory() as t:
        src = pathlib.Path(t)
        for rel, body in FIXTURE.items():
            (src / rel).parent.mkdir(parents=True, exist_ok=True)
            (src / rel).write_text(body, encoding="utf-8")
        rc = run(src)
        regs = (src / "com/example/att/Regs.java").read_text(encoding="utf-8")
        data = (src / "com/example/att/Data.java").read_text(encoding="utf-8")
        chk("refused a non-CompoundTag serializer -> exit 1", rc == 1)
        chk("type argument dropped", "new IAttachmentSerializer<Data>()" in regs)
        chk("read header + bridge lines",
            "public Data read(IAttachmentHolder holder, ValueInput nbtBridgeIn) {\n                    CompoundTag tag = "
            "NbtBridge.tag(nbtBridgeIn);\n                    HolderLookup.Provider provider = nbtBridgeIn.lookup();" in regs)
        chk("read body untouched", "d.deserializeNBT(provider, tag);" in regs)
        chk("write override", "public boolean write(Data data, ValueOutput nbtBridgeOut) {\n                    return "
            "NbtBridge.write(nbtBridgeOut, this.nbtBridge$write(data, NbtBridge.provider()));\n                }" in regs)
        chk("original write body kept in the private method",
            "private CompoundTag nbtBridge$write(Data data, HolderLookup.Provider provider) {\n                    return "
            "data.serializeNBT(provider);" in regs)
        chk("imports", all(f"import {w};" in regs for w in ("net.minecraft.world.level.storage.ValueInput",
                                                             "net.minecraft.world.level.storage.ValueOutput",
                                                             "com.example.att.compat.NbtBridge")))
        chk("INBTSerializable retargeted, class otherwise untouched",
            data == FIXTURE["com/example/att/Data.java"].replace("net.neoforged.neoforge.common.util.", "com.example.att.compat."))
        chk("compat INBTSerializable generated", (src / "com/example/att/compat/INBTSerializable.java").is_file())
        chk("bridge generated", "assumeMapUnsafe" in (src / "com/example/att/compat/NbtBridge.java").read_text(encoding="utf-8"))
        chk("non-CompoundTag serializer untouched", (src / "com/example/att/Other.java").read_text(encoding="utf-8") == FIXTURE["com/example/att/Other.java"])
        snap = {p: p.read_bytes() for p in src.rglob("*") if p.is_file()}
        run(src)
        chk("idempotent", snap == {p: p.read_bytes() for p in src.rglob("*") if p.is_file()})
    print("self-check:", "OK" if ok else "FAIL")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src")
    ap.add_argument("--package", help="where NbtBridge goes (default: <the @Mod class's package>.compat)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--self-check", action="store_true")
    a = ap.parse_args()
    if a.self_check:
        return self_check()
    if not a.src:
        ap.error("--src is required")
    return run(a.src, a.package, a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
